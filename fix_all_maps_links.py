resolved_urls = {}

print(f"Resolving {len(ALL_SPOTS)} locations via Google Maps Geocoding API...")
for name_key, query_jp in ALL_SPOTS:
    q_enc = urllib.parse.quote(query_jp)
    url = f"https://maps.googleapis.com/maps/api/geocode/json?address={q_enc}&language=ja&key={api_key}"
    try:
        req = urllib.request.urlopen(url, timeout=5)
        res = json.loads(req.read().decode('utf-8'))
        results = res.get('results', [])
        if results:
            r = results[0]
            place_id = r.get('place_id', '')
            loc = r.get('geometry', {}).get('location', {})
            canonical_url = f"https://www.google.com/maps/search/?api=1&query={loc.get('lat')},{loc.get('lng')}&query_place_id={place_id}"
            resolved_urls[name_key] = canonical_url
        else:
            resolved_urls[name_key] = f"https://www.google.com/maps/search/?api=1&query={q_enc}"
    except Exception as e:
        resolved_urls[name_key] = f"https://www.google.com/maps/search/?api=1&query={q_enc}"

print(f"Successfully resolved {len(resolved_urls)} permanent canonical Google Maps URLs!")

# Save to navigation_links_dict.json
with open('/home/owen/tokyo/navigation_links_dict.json', 'w', encoding='utf-8') as f:
    json.dump(resolved_urls, f, ensure_ascii=False, indent=2)

